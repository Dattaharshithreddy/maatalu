// Writes src/bedtime/audio.ts from the recordings in assets/bedtime (<id>.mp3 + <id>.json).
import { existsSync, readFileSync, writeFileSync } from 'node:fs';

const stories = JSON.parse(readFileSync('tools/bedtime/stories.json', 'utf8'));
const rows = [];
for (const { id } of stories) {
  const mp3 = `assets/bedtime/${id}.mp3`, meta = `assets/bedtime/${id}.json`;
  if (!existsSync(mp3) || !existsSync(meta)) continue;
  const { duration, starts } = JSON.parse(readFileSync(meta, 'utf8'));
  rows.push(`  ${JSON.stringify(id)}: { file: require('../../${mp3}'), duration: ${duration}, starts: ${JSON.stringify(starts)} },`);
}
writeFileSync('src/bedtime/audio.ts', `// Generated by .github/workflows/bedtime-audio.yml (tools/bedtime/collect.mjs). Do not edit by hand.
// Stories listed here play Harshith's recorded narration; the rest are read by the phone's Telugu voice.
/* eslint-disable */
export const BED_AUDIO: Record<string, { file: number; duration: number; starts: number[] }> = {
${rows.join('\n')}
};
`);
console.log(`${rows.length} of ${stories.length} stories have narration.`);
